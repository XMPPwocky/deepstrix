import sys
wide, mid, dst = sys.argv[1:4]
s = open(wide).read()
m = open(mid).read()
m = m.replace('__builtin_amdgcn_sffbh(0) * 0 + ', '')
a = s.index('typedef int   wm_v4i')
b = s.index('template <int MATS, int DOWN>\n__device__ __forceinline__ void wm_body')
head = s[:a]
tail = s[b:]
head = head.replace('#define WM_X_STRIDE    272u', '#define WM_X_STRIDE    272u  /* unused in the f16 arm */')
open(dst, 'w').write('// GENERATED by mkf16.py from cand_wide.hip + mid_f16.inc -- f16-WMMA arm (scale folded into perm LUT)\n'
                     + head + m + tail)
