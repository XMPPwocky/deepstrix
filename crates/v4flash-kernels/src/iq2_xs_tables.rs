/// Scalar reference dot: one IQ2_XS weight row against Q8_K activations.
///
/// Mirrors `ggml_vec_dot_iq2_xs_q8_K_generic` (llama.cpp
/// ggml/src/ggml-cpu/quants.c) exactly, including the final 0.125 factor.
/// Block layout (74 B): d(f16) | qs[32] u16 | scales[8] u8.
pub fn cpu_dot_iq2_xs_q8_k(n_blocks: usize, w_bytes: &[u8], y_bytes: &[u8]) -> f32 {
    assert_eq!(w_bytes.len(), n_blocks * BLOCK_IQ2_XS_BYTES);
    assert_eq!(y_bytes.len(), n_blocks * 292);

    let mut sumf = 0.0f32;
    for b in 0..n_blocks {
        let w = &w_bytes[b * BLOCK_IQ2_XS_BYTES..(b + 1) * BLOCK_IQ2_XS_BYTES];
        let y = &y_bytes[b * 292..(b + 1) * 292];

        let d = crate::iq2_xxs_tables::f16_to_f32(u16::from_le_bytes([w[0], w[1]]))
            * f32::from_le_bytes([y[0], y[1], y[2], y[3]]);
        // block_q8_K = f32 d (4 B) | int8 qs[256] | int16 bsums[16].
        let q8 = &y[4..260];

        let mut bsum = 0i32;
        for ib32 in 0..8 {
            let sc = w[66 + ib32];
            let ls1 = 2 * (sc & 0xf) as i32 + 1;
            let ls2 = 2 * (sc >> 4) as i32 + 1;
            // Two halves of the 32-block, each with its own 4-bit scale:
            // l in 0..2 -> ls1 (first 16 weights), l in 2..4 -> ls2.
            for (half, ls) in [(0usize, ls1), (2usize, ls2)] {
                let mut sumi = 0i32;
                for l in half..half + 2 {
                    let qi = 2 + (4 * ib32 + l) * 2;
                    let q2 = u16::from_le_bytes([w[qi], w[qi + 1]]);
                    let grid = IQ2XS_GRID[(q2 & 511) as usize].to_le_bytes();
                    let signs = KSIGNS_IQ2XS[(q2 >> 9) as usize];
                    let base = (4 * ib32 + l) * 8;
                    for j in 0..8 {
                        let v = grid[j] as i32 * q8[base + j] as i8 as i32;
                        sumi += if signs & KMASK_IQ2XS[j] != 0 { -v } else { v };
                    }
                }
                bsum += sumi * ls;
            }
        }
        sumf += d * bsum as f32;
    }
    0.125 * sumf
}
